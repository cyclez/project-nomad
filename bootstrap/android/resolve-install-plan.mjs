#!/usr/bin/env node

// resolve-install-plan.mjs
//
// Runs on the HOST (Mac/Linux/WSL). Reads a bootstrap.json manifest, resolves
// which payloads to install for a given device ABI and storage profile, and
// emits a flat install-plan.txt that the host script (usb-push.sh) consumes
// to pre-extract and push files to the device.
//
// The device never sees JSON. All extraction, checksum verification, and tar
// handling happen on the host. The on-device script only needs sh/mv/chmod.
//
// Usage:
//   node resolve-install-plan.mjs <bootstrap.json> <device-abi> [storage-profile]
//
// Output goes to stdout. Redirect to a file.

import { readFileSync } from 'node:fs'
import path from 'node:path'

function fatal(message) {
  console.error(`error: ${message}`)
  process.exit(1)
}

function usage() {
  console.error('Usage: node resolve-install-plan.mjs <bootstrap.json> <device-abi> [storage-profile]')
  console.error('  device-abi:       arm64-v8a | armeabi-v7a | x86_64')
  console.error('  storage-profile:  full | reduced | volatile (default: from manifest)')
  process.exit(64)
}

const args = process.argv.slice(2)
if (args.length < 2) usage()

const manifestPath = args[0]
const deviceAbi = args[1]
const requestedProfile = args[2] || null

// --- read manifest ---

let manifest
try {
  manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
} catch (e) {
  fatal(`cannot read ${manifestPath}: ${e.message}`)
}

if (manifest.schema_version !== '1.0') {
  fatal(`unsupported schema_version "${manifest.schema_version}"`)
}

// --- validate ABI ---

const supportedAbis = manifest.compatibility?.supported_abis || []
if (!supportedAbis.includes(deviceAbi)) {
  fatal(`device ABI "${deviceAbi}" not in supported ABIs [${supportedAbis.join(', ')}]`)
}

// --- resolve storage profile ---

const profileId = requestedProfile || manifest.defaults?.storage_profile
if (!profileId) {
  fatal('no storage profile specified and no default in manifest')
}

const profile = (manifest.storage_profiles || []).find(p => p.id === profileId)
if (!profile) {
  const available = (manifest.storage_profiles || []).map(p => p.id).join(', ')
  fatal(`storage profile "${profileId}" not found (available: ${available})`)
}

const keepTags = new Set(profile.keep_tags || [])
const dropTags = new Set(profile.drop_tags || [])

// --- resolve payloads ---

function shouldInstall(payload) {
  // ABI filter first: skip binaries for wrong architecture
  if (payload.abi !== 'any' && payload.abi !== deviceAbi) {
    return false
  }

  // Required payloads always install (after ABI filter)
  if (payload.required) {
    return true
  }

  // Tag-based profile filter
  // Per ANDROID_BOOTSTRAP_FORMAT.md: drop_tags wins over keep_tags
  const hasDrop = (payload.install_tags || []).some(t => dropTags.has(t))
  if (hasDrop) return false

  const hasKeep = (payload.install_tags || []).some(t => keepTags.has(t))
  return hasKeep
}

function actionForPayload(payload) {
  // Tar archives need extraction; everything else is a raw copy
  if (payload.path.endsWith('.tar')) return 'extract'
  return 'copy'
}

const selected = (manifest.payloads || []).filter(shouldInstall)

if (selected.length === 0) {
  fatal('no payloads selected — check ABI and storage profile')
}

// --- emit plan ---

const lines = []

lines.push('# emergency-nomad install plan')
lines.push('# generated by resolve-install-plan.mjs — do not edit')
lines.push(`# bundle=${manifest.bundle.id} version=${manifest.bundle.version} profile=${profileId} abi=${deviceAbi}`)
lines.push('# format: ACTION SOURCE_PATH DEST_SUBDIR SHA256')
lines.push('#')

let actionCount = 0

for (const p of selected) {
  lines.push(`${actionForPayload(p)} ${p.path} ${p.kind} ${p.sha256}`)
  actionCount++
}

for (const input of manifest.upstream_inputs || []) {
  lines.push(`seed ${input.path} collections -`)
  actionCount++
}

// Config entries — read by on-device-install.sh to write runtime.conf
lines.push(`# config: loopback_base_url=${manifest.defaults.loopback_base_url}`)
lines.push(`# config: seed_network_policy=${manifest.defaults.seed_network_policy}`)
lines.push(`# config: oneshot_enabled=${manifest.defaults.oneshot_enabled}`)
lines.push(`# config: storage_profile=${profileId}`)
lines.push(`# config: bundle_id=${manifest.bundle.id}`)
lines.push(`# config: bundle_version=${manifest.bundle.version}`)
lines.push(`# config: installed_abi=${deviceAbi}`)

lines.push(`# total_actions=${actionCount}`)

process.stdout.write(lines.join('\n') + '\n')
